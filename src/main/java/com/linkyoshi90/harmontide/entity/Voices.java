package com.linkyoshi90.harmontide.entity;

import com.linkyoshi90.harmontide.registry.SpeciesVoiceTable;
import net.minecraft.core.registries.BuiltInRegistries;
import net.minecraft.resources.ResourceLocation;
import net.minecraft.sounds.SoundEvent;
import net.minecraft.world.entity.LivingEntity;

import javax.annotation.Nullable;
import java.util.ArrayList;
import java.util.HashMap;
import java.util.List;
import java.util.Map;
import java.util.function.Function;
import java.util.function.Supplier;

/**
 * Per-species voices (2026-11-10): every girl and harpy species that still speaks with a vanilla mob's voice has her own sound events,
 * entity.&lt;species&gt;.ambient / hurt / death / eat. In sounds.json each points at the vanilla sound she used before (a "type": "event"
 * redirect), so nothing sounds different until a real recording is dropped in: put the .ogg under assets/harmontide/sounds/&lt;species&gt;/
 * and point that event at it. The table of which vanilla sound each species used (registry/SpeciesVoiceTable) is generated by
 * tools/gen_species_voices.py from what the species return (gametest VoiceTests checks it is current).
 * <p>
 * The swap happens where any sound she makes is played (Voiced.playSound overrides): a sound that is one of her slots' vanilla
 * sounds is played as her own event instead. A family that picks a different sound in some state (a mermaid out of the water) keeps
 * that one.
 */
public final class Voices {
    public static final List<String> SLOTS = List.of("hurt", "ambient", "eat", "death");

    /** One species' slot: the vanilla sound it stood for, and her own event. */
    private record Slot(String slot, Supplier<SoundEvent> event) {
    }

    /** "species|vanilla sound id" to her slots that used it (usually one). */
    private static final Map<String, List<Slot>> BY_SOUND = new HashMap<>();
    private static boolean registered;

    private Voices() {
    }

    /** Registers every table row's event with the given registrar (ModSounds, at class init). */
    public static void registerAll(Function<String, Supplier<SoundEvent>> register) {
        if (registered) return;
        registered = true;
        for (String[] row : SpeciesVoiceTable.ROWS) {
            Supplier<SoundEvent> event = register.apply(name(row[0], row[1]));
            BY_SOUND.computeIfAbsent(row[0] + "|" + row[2], k -> new ArrayList<>()).add(new Slot(row[1], event));
        }
    }

    public static String name(String species, String slot) {
        return "entity." + species + "." + slot;
    }

    /** The sound to play for this one: her own event if the sound is one of her slots' vanilla sounds, else the sound itself. */
    public static SoundEvent voice(LivingEntity who, SoundEvent sound) {
        if (BY_SOUND.isEmpty()) return sound;
        List<Slot> slots = BY_SOUND.get(BuiltInRegistries.ENTITY_TYPE.getKey(who.getType()).getPath() + "|" + sound.getLocation());
        if (slots == null) return sound;
        Slot pick = slots.get(0);
        if (slots.size() > 1 && who.isDeadOrDying()) for (Slot s : slots) if (s.slot().equals("death")) pick = s;
        return pick.event().get();
    }

    /** Her own event for a slot, or null if she has none (tests). */
    @Nullable
    public static SoundEvent own(String species, String slot) {
        for (List<Slot> list : BY_SOUND.values()) for (Slot s : list) {
            if (s.slot().equals(slot) && s.event().get().getLocation().getPath().equals(name(species, slot))) return s.event().get();
        }
        return null;
    }

    /** The species' sound for a slot as she picks it now, for the table (null if she has none). */
    @Nullable
    public static ResourceLocation id(@Nullable SoundEvent sound) {
        return sound == null ? null : sound.getLocation();
    }

    /** Implemented by the girl and harpy base classes: the sound she picks for a slot right now. */
    public interface Voiced {
        @Nullable
        SoundEvent slotSound(String slot);
    }
}
