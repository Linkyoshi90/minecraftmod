/**
 * Small, sociable settlement harpy. Hops and flutters around villages and farms, sings from rooftops,
 * bathes in shallow water, birdbaths (water cauldrons) and sand, tags along with friendly mobs, waits by
 * fields begging for seeds/bread, picks up (and now and then snatches) small things, and flees from monsters,
 * cats and sprinting players. Feed her or give her a birdbath and she adopts the spot as home and keeps coming back.
 */
public class SparrowHarpy extends AbstractHarpy {
    private static final EntityDataAccessor<Byte> DATA_VARIANT =
            SynchedEntityData.defineId(SparrowHarpy.class, EntityDataSerializers.BYTE);
    /** One in this many sparrows is the rare sky-blue PAPI variant, wherever she spawns. */
    private static final int PAPI_RARITY = 25;
    /** How far she roams from a home during the day. */
    private static final double HOME_RADIUS = 32.0;

    /** Set when fed; the sing goal picks it up and sings on the spot. */
    private boolean happySongQueued;

    /** Colour variants; each has its own texture, generated by tools/gen_sparrow_harpy.py. Saved by name, synced by ordinal. */
    public enum Variant {
        HOUSE("house"), SAND("sand"), SLATE("slate"), TREE("tree"), PAPI("papi");

        private final String name;

        Variant(String name) {
            this.name = name;
        }

        public String getSerializedName() {
            return this.name;
        }

        public static Variant byName(String name) {
            for (Variant v : values()) if (v.name.equals(name)) return v;
            return HOUSE;
        }

        /** Desert sparrows are sandy, northern ones slate-grey, woodland ones rufous; villages get the classic house sparrow. */
        public static Variant forBiome(Holder<Biome> biome) {
            if (biome.is(Tags.Biomes.IS_SANDY) || biome.is(Tags.Biomes.IS_DRY_OVERWORLD)) return SAND;
            if (biome.is(Tags.Biomes.IS_COLD_OVERWORLD) || biome.is(Tags.Biomes.IS_TAIGA) || biome.is(Tags.Biomes.IS_SNOWY)) return SLATE;
            if (biome.is(Tags.Biomes.IS_FOREST)) return TREE;
            return HOUSE;
        }
    }

    /** Shares one variant across a spawn group so flocks match. */
    private record VariantGroupData(Variant variant) implements SpawnGroupData {}

    public SparrowHarpy(EntityType<? extends SparrowHarpy> type, Level level) {
        super(type, level);
    }

    public static AttributeSupplier.Builder createAttributes() {
        return Mob.createMobAttributes()
                .add(Attributes.MAX_HEALTH, 8.0)
                .add(Attributes.MOVEMENT_SPEED, 0.2)
                .add(Attributes.FLYING_SPEED, 0.4)
                .add(Attributes.FOLLOW_RANGE, 24.0);
    }

    /**
     * Daylight on grass/farmland/sand/paths. Sparrows are settlement birds, so away from villages
     * two out of three natural spawn attempts are rejected.
     */
    public static boolean checkSparrowHarpySpawnRules(EntityType<SparrowHarpy> type, ServerLevelAccessor level,
                                                      MobSpawnType spawnType, BlockPos pos, RandomSource random) {
        if (!level.getBlockState(pos.below()).is(ModTags.SPARROW_HARPY_SPAWNABLE_ON)) return false;
        if (level.getRawBrightness(pos, 0) <= 8) return false;
        if (spawnType == MobSpawnType.NATURAL && !level.getLevel().isVillage(pos)) {
            return random.nextInt(3) == 0;
        }
        return true;
    }

    @Override
    protected String species() {
        return "sparrow_harpy";
    }

    @Override
    protected String actionAnimation(Action action) {
        return switch (action) {
            case SINGING -> "sing";
            case BATHING -> "bathe";
            default -> null;
        };
    }

    /** Bright major-pentatonic notes for singing along to a jukebox. */
    private static final int[] SING_ALONG = {12, 14, 16, 19, 21, 24};

    @Override
    protected void registerGoals() {
        this.goalSelector.addGoal(0, new FloatGoal(this));
        this.goalSelector.addGoal(1, new PanicGoal(this, 1.25));
        this.goalSelector.addGoal(2, new AvoidEntityGoal<>(this, Monster.class, 8.0F, 1.0, 1.4));
        this.goalSelector.addGoal(2, new AvoidEntityGoal<>(this, Cat.class, 6.0F, 1.0, 1.3));
        this.goalSelector.addGoal(2, new AvoidEntityGoal<>(this, Ocelot.class, 6.0F, 1.0, 1.3));
        // Easily startled: anyone running at her sends her flying, unless they're holding a treat.
        this.goalSelector.addGoal(2, new AvoidEntityGoal<>(this, Player.class, 5.0F, 1.0, 1.3, this::isStartledBy));
        // A jukebox playing nearby: she flutters over and sings along with it (and so does the rest of the flock).
        this.goalSelector.addGoal(3, new ListenToMusicGoal(this, 1.0, 2.5, Action.SINGING, h -> true, (h, jukebox, t) -> {
            if (t % 8 == 0 && h.getRandom().nextInt(4) != 0) {
                ListenToMusicGoal.note(h, ModSounds.SPARROW_SING.get(), SING_ALONG[h.getRandom().nextInt(SING_ALONG.length)], 0.7F);
            }
        }, null));
        // Above tempting so a fed sparrow sings her thanks even while you're still holding seeds.
        this.goalSelector.addGoal(3, new SingGoal(this));
        // Dangle bread in front of her long enough and she may just grab it.
        this.goalSelector.addGoal(3, new SnatchGoal(this, 1.2, SnatchGoal.From.HAND, 600, 2400, p -> true));
        this.goalSelector.addGoal(4, new RoostInHopperGoal(this));
        this.goalSelector.addGoal(4, new TemptGoal(this, 1.0, Ingredient.of(ModTags.SPARROW_HARPY_FOOD), true));
        this.goalSelector.addGoal(5, new SeekItemGoal(this, 1.0, 8.0));
        this.goalSelector.addGoal(5, new ReturnHomeGoal(this, 1.0, HOME_RADIUS));
        this.goalSelector.addGoal(6, new BatheGoal(this, 1.0));
        this.goalSelector.addGoal(6, new BegAtFarmGoal(this, 1.0));
        this.goalSelector.addGoal(7, new FollowFriendlyMobGoal(this, 1.0, 3.0F, 10.0F, SparrowHarpy::isFriendlyMob));
        this.goalSelector.addGoal(8, new WaterAvoidingRandomFlyingGoal(this, 1.0));
        this.goalSelector.addGoal(9, new LookAtPlayerGoal(this, Player.class, 8.0F));
        this.goalSelector.addGoal(10, new RandomLookAroundGoal(this));
    }

    private static boolean isFriendlyMob(Mob self, Mob other) {
        return other instanceof Animal || other instanceof AbstractVillager || other instanceof AbstractGolem || other.getType() == self.getType();
    }

    private boolean isStartledBy(LivingEntity entity) {
        return entity instanceof Player player && player.isSprinting() && !player.isSpectator()
                && !this.isEdible(player.getMainHandItem()) && !this.isEdible(player.getOffhandItem());
    }

    @Override
    public boolean isEdible(ItemStack stack) {
        return stack.is(ModTags.SPARROW_HARPY_FOOD);
    }

    @Override
    public boolean likesToCarry(ItemStack stack) {
        return stack.is(ModTags.SPARROW_HARPY_TRINKETS);
    }

    // --- variant ------------------------------------------------------------------------------------------------

    @Override
    protected void defineSynchedData(SynchedEntityData.Builder builder) {
        super.defineSynchedData(builder);
        builder.define(DATA_VARIANT, (byte) Variant.HOUSE.ordinal());
    }

    public Variant getVariant() {
        return Variant.values()[this.entityData.get(DATA_VARIANT)];
    }

    public void setVariant(Variant variant) {
        this.entityData.set(DATA_VARIANT, (byte) variant.ordinal());
    }

    @Override
    public void addAdditionalSaveData(CompoundTag tag) {
        super.addAdditionalSaveData(tag);
        tag.putString("Variant", this.getVariant().getSerializedName());
    }

    @Override
    public void readAdditionalSaveData(CompoundTag tag) {
        super.readAdditionalSaveData(tag);
        this.setVariant(Variant.byName(tag.getString("Variant")));
    }

    // --- roosting on a hopper ------------------------------------------------------------------------------------

    /** She nests in the bowl of a hopper (see {@link RoostInHopperGoal}). */
    @Override
    public boolean roostsInHoppers() {
        return true;
    }

    @Override
    protected ItemStack unfertilisedEgg() {
        return new ItemStack(ModItems.SPARROW_EGG.get());
    }

    /** A moulted feather or a twig from her nesting: half of what a fletcher needs (the gulls bring the flint). */
    @Override
    protected ItemStack roostDrop() {
        return new ItemStack(this.random.nextBoolean() ? Items.FEATHER : Items.STICK);
    }

    @Override
    public SpawnGroupData finalizeSpawn(ServerLevelAccessor level, DifficultyInstance difficulty, MobSpawnType spawnType,
                                        @Nullable SpawnGroupData groupData) {
        Variant variant;
        if (groupData instanceof VariantGroupData group) {
            variant = group.variant();
        } else {
            variant = Variant.forBiome(level.getBiome(this.blockPosition()));
            groupData = new VariantGroupData(variant);
        }
        if (!this.hasVariantFromData()) this.setVariant(this.random.nextInt(PAPI_RARITY) == 0 ? Variant.PAPI : variant);
        return super.finalizeSpawn(level, difficulty, spawnType, groupData);
    }

    // --- feeding, home ------------------------------------------------------------------------------------------

    public boolean consumeHappySong() {
        boolean queued = this.happySongQueued;
        this.happySongQueued = false;
        return queued;
    }

    @Override
    protected InteractionResult mobInteract(Player player, InteractionHand hand) {
        ItemStack stack = player.getItemInHand(hand);
        if (!this.isEdible(stack)) return super.mobInteract(player, hand);

        if (this.level() instanceof ServerLevel server) {
            stack.consume(1, player);
            this.heal(2.0F);
            this.addAffection(player, 1);
            this.happySongQueued = true;
            // A place where someone feeds her is a place worth coming back to.
            this.setHomePos(this.blockPosition());
            this.playSound(this.getEatSound(), 1.0F, this.getVoicePitch());
            server.sendParticles(ParticleTypes.HEART, this.getX(), this.getY() + this.getBbHeight() + 0.2, this.getZ(),
                    3, 0.3, 0.2, 0.3, 0.0);
        }
        return InteractionResult.sidedSuccess(this.level().isClientSide);
    }

    @Override
    protected void onPetted(Player player) {
        super.onPetted(player);
        if (this.onGround()) this.getJumpControl().jump(); // a happy little hop
    }

    @Override
    public Component describeBond(Player player) {
        int affection = this.getAffection(player);
        String level = affection >= 8 ? "adores" : affection >= 3 ? "likes" : affection >= 1 ? "curious" : "stranger";
        return Component.translatable("bond.harmontide.sparrow." + level, affection);
    }

    @Override
    public void onBathed(BlockPos pos, BlockState state) {
        // A birdbath makes a garden home.
        if (state.is(Blocks.WATER_CAULDRON)) this.setHomePos(pos.above());
    }

    // --- sounds -------------------------------------------------------------------------------------------------

    @Override
    protected SoundEvent getAmbientSound() {
        return this.getAction() == Action.SINGING ? null : ModSounds.SPARROW_AMBIENT.get();
    }

    @Override
    protected SoundEvent getHurtSound(DamageSource source) {
        return ModSounds.SPARROW_HURT.get();
    }

    @Override
    protected SoundEvent getDeathSound() {
        return ModSounds.SPARROW_DEATH.get();
    }

    @Override
    protected SoundEvent getEatSound() {
        return ModSounds.SPARROW_EAT.get();
    }

    @Override
    public SoundEvent getChirpSound() {
        return ModSounds.SPARROW_AMBIENT.get(); // her ambient sound is muted while singing
    }

    /** A hatchling from a clutch: any of her species' colours. */
    @Override
    public void plainVariant() {
        this.setVariant(Variant.values()[0]);
    }

    @Override
    public void randomizeVariant() {
        Variant[] all = Variant.values();
        this.setVariant(all[this.random.nextInt(all.length)]);
    }
}
