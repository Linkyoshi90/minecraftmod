#!/usr/bin/env python3
"""Each species' place in the food web (2026-11-13, entity/FoodWeb#role), read from her concept (family_concepts*.py): her ecology and
interaction lines are scored for hunting, fishing, carrion and plant words, and the strongest wins. Written as registry/DietTable.java;
species whose text says nothing either way are left out (FoodWeb falls back on her clade).

    python tools/gen_diet_table.py
"""
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import family_concepts as C  # noqa: E402
import family_concepts_harmontide  # noqa: E402,F401  (adds the Harmontide species)

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "src", "main", "java", "com", "linkyoshi90", "harmontide", "registry", "DietTable.java")

WORDS = {
    "SCAVENGER": [r"rotten flesh", r"carrion", r"scaveng", r"corpse", r"\bbones?\b.*\bdead\b"],
    "FISHER": [r"\bfish", r"\bcod\b", r"salmon", r"squid", r"shellfish", r"\bclams?\b", r"\bkrill\b"],
    "HUNTER": [r"\bhunts?\b", r"\bhunting\b", r"\bprey\b", r"chicken", r"mutton", r"\bbeef\b", r"porkchop", r"\bpork\b", r"\brabbits?\b",
               r"raw meat", r"\bmeat\b", r"pounce", r"stalks?\b"],
    "GRAZER": [r"\bgrass", r"\bgraz", r"berr(y|ies)", r"\bfruit", r"apple", r"wheat", r"carrot", r"\bleaves\b", r"bamboo", r"flowers?",
               r"nectar", r"\bseeds?\b", r"\bhay\b", r"melon", r"\bbrows", r"\bmoss\b", r"lichen", r"\broots?\b"],
}
ORDER = ["HUNTER", "FISHER", "SCAVENGER", "GRAZER"]

# when she is up and about (entity/girl/AbstractMonsterGirl#rhythm): the strongest wins, nothing said = by day
RHYTHM_WORDS = {
    "NOCTURNAL": [r"nocturnal", r"\bat night\b", r"\bby night\b", r"after dark", r"\bnights?\b", r"moonlit", r"moonlight"],
    "CREPUSCULAR": [r"\bdusk\b", r"\bdawn\b", r"twilight", r"crepuscular", r"sunset", r"sunrise", r"half-light"],
    "CATHEMERAL": [r"\bnaps?\b", r"cathemeral", r"any hour", r"day and night", r"\bdozes?\b", r"round the clock"],
    "DIURNAL": [r"\bby day\b", r"daytime", r"midday", r"\bnoon\b", r"\bbasks?\b", r"sunbath", r"in the sun\b"],
}
RHYTHMS = ["NOCTURNAL", "CREPUSCULAR", "CATHEMERAL", "DIURNAL"]
RHYTHM_OUT = os.path.join(ROOT, "src", "main", "java", "com", "linkyoshi90", "harmontide", "registry", "RhythmTable.java")


def role(text):
    t = text.lower()
    score = {r: sum(len(re.findall(w, t)) for w in ws) for r, ws in WORDS.items()}
    best = max(ORDER, key=lambda r: (score[r], -ORDER.index(r)))
    return best if score[best] > 0 else None


def rhythm(text):
    t = text.lower()
    score = {r: sum(len(re.findall(w, t)) for w in ws) for r, ws in RHYTHM_WORDS.items()}
    best = max(RHYTHMS, key=lambda r: (score[r], -RHYTHMS.index(r)))
    return best if score[best] > 0 and best != "DIURNAL" else None


def write_rhythms():
    rows = []
    for fam in C.FAMILIES:
        for sp in fam["species"]:
            text = " ".join(str(sp.get(k, "")) for k in ("ecology", "interaction", "temperament", "group", "tag"))
            r = rhythm(text)
            if r:
                rows.append((sp["id"], r))
    lines = ",\n".join(f'            Map.entry("{sp}", "{r}")' for sp, r in sorted(rows))
    java = f"""package com.linkyoshi90.harmontide.registry;

import java.util.Map;

/** Generated by tools/gen_diet_table.py: each species' daily rhythm when it isn't by day, read from her concept. Do not edit. */
public final class RhythmTable {{
    public static final Map<String, String> RHYTHM = Map.ofEntries(
{lines});

    private RhythmTable() {{}}
}}
"""
    open(RHYTHM_OUT, "w", encoding="utf-8", newline="\n").write(java)
    from collections import Counter
    print(len(rows), "rhythms", Counter(r for _, r in rows))


NEED_WORDS = {
    "SHADE": [r"\bshad(e|y)\b", r"canopy", r"under (the )?trees", r"dark forest", r"\bgloom"],
    "SUN": [r"\bbasks?\b", r"sunbath", r"\bsunny\b", r"in the sun\b", r"sunlight"],
    "WET": [r"\bponds?\b", r"\brivers?\b", r"\bstreams?\b", r"swamp", r"marsh", r"\bbogs?\b", r"wetland", r"\bdamp\b", r"\blakes?\b", r"\bmud\b"],
    "DRY": [r"desert", r"\bdunes?\b", r"\barid\b", r"badlands"],
    "HIGH": [r"\bcliffs?\b", r"\bpeaks?\b", r"mountain", r"\bledges?\b", r"summit", r"\bcrags?\b", r"highest"],
    "DEEP": [r"\bcaves?\b", r"cavern", r"underground", r"deep dark", r"\btunnels?\b"],
    "COLD": [r"\bsnow", r"\bfrost", r"\bice\b", r"\bicy\b", r"tundra", r"arctic", r"frozen"],
    "HOT": [r"volcan", r"\blava\b", r"nether", r"scorching", r"blistering"],
}
BIOME_NEEDS = [("dark_forest", "SHADE"), ("swamp", "WET"), ("mangrove", "WET"), ("river", "WET"), ("desert", "DRY"), ("badlands", "DRY"),
               ("peaks", "HIGH"), ("windswept", "HIGH"), ("caves", "DEEP"), ("deep_dark", "DEEP"), ("dripstone", "DEEP"), ("snowy", "COLD"),
               ("frozen", "COLD"), ("ice", "COLD"), ("grove", "COLD"), ("nether", "HOT"), ("basalt", "HOT"), ("crimson", "HOT"), ("warped", "HOT"),
               ("savanna", "SUN"), ("desert", "SUN")]
HABITAT_OUT = os.path.join(ROOT, "src", "main", "java", "com", "linkyoshi90", "harmontide", "registry", "HabitatTable.java")


def write_habitats():
    """each species' one or two strongest needs (entity/Microhabitats), from her biomes and her concept's words; water kinds left out."""
    rows = []
    for fam in C.FAMILIES:
        if fam["id"] in ("merfolk", "mollusk", "crustacean"):
            continue
        for sp in fam["species"]:
            text = " ".join(str(sp.get(k, "")) for k in ("ecology", "group", "tag", "interaction")).lower()
            score = {n: sum(len(re.findall(w, text)) for w in ws) for n, ws in NEED_WORDS.items()}
            for b in sp.get("biomes", []):
                for key, need in BIOME_NEEDS:
                    if key in b:
                        score[need] += 1
            if score["COLD"] and score["HOT"]:
                score["HOT" if score["HOT"] < score["COLD"] else "COLD"] = 0
            if score["WET"] and score["DRY"]:
                score["DRY" if score["DRY"] < score["WET"] else "WET"] = 0
            if score["SUN"] and score["SHADE"]:
                score["SHADE" if score["SHADE"] < score["SUN"] else "SUN"] = 0
            needs = [n for n, s in sorted(score.items(), key=lambda kv: -kv[1]) if s > 0][:2]
            if needs:
                rows.append((sp["id"], needs))
    lines = ",\n".join(f'            Map.entry("{sp}", List.of({", ".join(chr(34) + n + chr(34) for n in ns)}))' for sp, ns in sorted(rows))
    java = f"""package com.linkyoshi90.harmontide.registry;

import java.util.List;
import java.util.Map;

/** Generated by tools/gen_diet_table.py: each species' microhabitat needs (entity/Microhabitats), from her biomes and concept. Do not edit. */
public final class HabitatTable {{
    public static final Map<String, List<String>> NEEDS = Map.ofEntries(
{lines});

    private HabitatTable() {{}}
}}
"""
    open(HABITAT_OUT, "w", encoding="utf-8", newline="\n").write(java)
    from collections import Counter
    print(len(rows), "habitats", Counter(n for _, ns in rows for n in ns))


def main():
    write_rhythms()
    write_habitats()
    rows = []
    for fam in C.FAMILIES:
        for sp in fam["species"]:
            text = " ".join(str(sp.get(k, "")) for k in ("ecology", "interaction"))
            r = role(text)
            if r:
                rows.append((sp["id"], r))
    lines = ",\n".join(f'            Map.entry("{sp}", "{r}")' for sp, r in sorted(rows))
    pollinators, seeders = [], []
    for fam in C.FAMILIES:
        for sp in fam["species"]:
            text = " ".join(str(sp.get(k, "")) for k in ("ecology", "interaction", "signature")).lower()
            flowery = re.search(r"nectar|pollen|pollinat|\bblossoms?\b|\bblooms?\b|\bflowers?\b|meadow", text)
            named = re.search(r"bee|butterfl|moth|hummingbird|pixi|fairy|sprite|nymph", sp["id"])
            if fam["id"] in ("bug", "bat", "elf") and (flowery or named) and not re.search(r"mantis|ant_|spider|wasp|mosquito|tick|antlion|cicada|beetle|tardigrade", sp["id"]):
                pollinators.append(sp["id"])
            if re.search(r"\bfruits?\b|berr(y|ies)|\bapples?\b|\bnuts?\b|acorns?|\bseeds?\b|melons?", text) and fam["id"] not in ("merfolk", "mollusk", "crustacean", "slime", "construct"):
                seeders.append(sp["id"])
    pol = ", ".join(f'"{s}"' for s in sorted(pollinators))
    seed = ", ".join(f'"{s}"' for s in sorted(seeders))
    java = f"""package com.linkyoshi90.harmontide.registry;

import java.util.Map;
import java.util.Set;

/** Generated by tools/gen_diet_table.py: each species' food-web role, read from her concept, and who pollinates and spreads seeds. Do not edit. */
public final class DietTable {{
    public static final Map<String, String> ROLE = Map.ofEntries(
{lines});
    /** Nectar and pollen kinds (entity/Pollination). */
    public static final Set<String> POLLINATORS = Set.of({pol});
    /** Fruit, nut and seed eaters who carry seeds off (entity/Pollination). */
    public static final Set<String> SEEDERS = Set.of({seed});

    private DietTable() {{}}
}}
"""
    print(len(pollinators), "pollinators", len(seeders), "seeders", pollinators)
    open(OUT, "w", encoding="utf-8", newline="\n").write(java)
    from collections import Counter
    print(len(rows), "species", Counter(r for _, r in rows))


if __name__ == "__main__":
    main()
