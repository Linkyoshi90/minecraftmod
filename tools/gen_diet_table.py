#!/usr/bin/env python3
"""Each species' place in the food web (2026-11-13, entity/FoodWeb#role), read from her concept (family_concepts*.py): her ecology and
interaction lines are scored for hunting, fishing, carrion and plant words, and the strongest wins. Written as registry/DietTable.java;
species whose text says nothing either way are left out (FoodWeb falls back on her clade).

    python tools/gen_diet_table.py
"""
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import family_concepts as C  # noqa: E402
import family_concepts_harmontide  # noqa: E402,F401  (adds the Harmontide species)

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "src", "main", "java", "com", "linkyoshi90", "harmontide", "registry", "DietTable.java")

WORDS = {
    "SCAVENGER": [r"rotten flesh", r"carrion", r"scaveng", r"corpse", r"\bbones?\b.*\bdead\b"],
    "FISHER": [r"\bfish", r"\bcod\b", r"salmon", r"squid", r"shellfish", r"\bclams?\b", r"\bkrill\b"],
    "HUNTER": [r"\bhunts?\b", r"\bhunting\b", r"\bprey\b", r"chicken", r"mutton", r"\bbeef\b", r"porkchop", r"\bpork\b", r"\brabbits?\b",
               r"raw meat", r"\bmeat\b", r"pounce", r"stalks?\b"],
    "GRAZER": [r"\bgrass", r"\bgraz", r"berr(y|ies)", r"\bfruit", r"apple", r"wheat", r"carrot", r"\bleaves\b", r"bamboo", r"flowers?",
               r"nectar", r"\bseeds?\b", r"\bhay\b", r"melon", r"\bbrows", r"\bmoss\b", r"lichen", r"\broots?\b"],
}
ORDER = ["HUNTER", "FISHER", "SCAVENGER", "GRAZER"]

# when she is up and about (entity/girl/AbstractMonsterGirl#rhythm): the strongest wins, nothing said = by day
RHYTHM_WORDS = {
    "NOCTURNAL": [r"nocturnal", r"\bat night\b", r"\bby night\b", r"after dark", r"\bnights?\b", r"moonlit", r"moonlight"],
    "CREPUSCULAR": [r"\bdusk\b", r"\bdawn\b", r"twilight", r"crepuscular", r"sunset", r"sunrise", r"half-light"],
    "CATHEMERAL": [r"\bnaps?\b", r"cathemeral", r"any hour", r"day and night", r"\bdozes?\b", r"round the clock"],
    "DIURNAL": [r"\bby day\b", r"daytime", r"midday", r"\bnoon\b", r"\bbasks?\b", r"sunbath", r"in the sun\b"],
}
RHYTHMS = ["NOCTURNAL", "CREPUSCULAR", "CATHEMERAL", "DIURNAL"]
RHYTHM_OUT = os.path.join(ROOT, "src", "main", "java", "com", "linkyoshi90", "harmontide", "registry", "RhythmTable.java")


def role(text):
    t = text.lower()
    score = {r: sum(len(re.findall(w, t)) for w in ws) for r, ws in WORDS.items()}
    best = max(ORDER, key=lambda r: (score[r], -ORDER.index(r)))
    return best if score[best] > 0 else None


def rhythm(text):
    t = text.lower()
    score = {r: sum(len(re.findall(w, t)) for w in ws) for r, ws in RHYTHM_WORDS.items()}
    best = max(RHYTHMS, key=lambda r: (score[r], -RHYTHMS.index(r)))
    return best if score[best] > 0 and best != "DIURNAL" else None


def write_rhythms():
    rows = []
    for fam in C.FAMILIES:
        for sp in fam["species"]:
            text = " ".join(str(sp.get(k, "")) for k in ("ecology", "interaction", "temperament", "group", "tag"))
            r = rhythm(text)
            if r:
                rows.append((sp["id"], r))
    lines = ",\n".join(f'            Map.entry("{sp}", "{r}")' for sp, r in sorted(rows))
    java = f"""package com.linkyoshi90.harmontide.registry;

import java.util.Map;

/** Generated by tools/gen_diet_table.py: each species' daily rhythm when it isn't by day, read from her concept. Do not edit. */
public final class RhythmTable {{
    public static final Map<String, String> RHYTHM = Map.ofEntries(
{lines});

    private RhythmTable() {{}}
}}
"""
    open(RHYTHM_OUT, "w", encoding="utf-8", newline="\n").write(java)
    from collections import Counter
    print(len(rows), "rhythms", Counter(r for _, r in rows))


def main():
    write_rhythms()
    rows = []
    for fam in C.FAMILIES:
        for sp in fam["species"]:
            text = " ".join(str(sp.get(k, "")) for k in ("ecology", "interaction"))
            r = role(text)
            if r:
                rows.append((sp["id"], r))
    lines = ",\n".join(f'            Map.entry("{sp}", "{r}")' for sp, r in sorted(rows))
    java = f"""package com.linkyoshi90.harmontide.registry;

import java.util.Map;

/** Generated by tools/gen_diet_table.py: each species' food-web role, read from her concept. Do not edit. */
public final class DietTable {{
    public static final Map<String, String> ROLE = Map.ofEntries(
{lines});

    private DietTable() {{}}
}}
"""
    open(OUT, "w", encoding="utf-8", newline="\n").write(java)
    from collections import Counter
    print(len(rows), "species", Counter(r for _, r in rows))


if __name__ == "__main__":
    main()
