#!/usr/bin/env python3
"""Per-species voices (2026-11-10, entity/Voices): every girl and harpy species still on a vanilla mob's voice gets her own sound events,
entity.<species>.ambient / hurt / death / eat, each pointing (a "type": "event" redirect in sounds.json) at the vanilla sound she used,
so nothing sounds different until a real recording replaces it.

    uv run --no-project --with pillow python tools/gen_species_voices.py <species_voices_dump.txt>

The dump comes from the GameTest VoiceTests.everySpeciesHasHerVoice, which writes it (and fails) whenever the table is out of date.
Writes registry/SpeciesVoiceTable.java, the sounds.json entries and the subtitles. An entry in sounds.json that no longer is a plain
redirect (a real recording was put in) is never overwritten.
"""
import json
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from gen_milk_assets import add_lang  # noqa: E402

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
ASSETS = os.path.join(ROOT, "src", "main", "resources", "assets", "harmontide")
TABLE = os.path.join(ROOT, "src", "main", "java", "com", "linkyoshi90", "harmontide", "registry", "SpeciesVoiceTable.java")
VERB = {"ambient": "chatters", "hurt": "hurts", "death": "dies", "eat": "eats"}


def redirect(entry):
    """Whether a sounds.json entry is still only this generator's redirect to a vanilla event."""
    s = entry.get("sounds", [])
    return len(s) == 1 and isinstance(s[0], dict) and s[0].get("type") == "event"


def main(dump):
    rows = []
    with open(dump, encoding="utf-8") as fh:
        for line in fh:
            line = line.strip()
            if line:
                rows.append(line.split("|"))
    rows.sort()
    before = set()                                                         # what the last run made (only those may go)
    if os.path.exists(TABLE):
        import re
        with open(TABLE, encoding="utf-8") as fh:
            for a, b in re.findall(r'\{"([a-z0-9_]+)", "([a-z]+)", "[^"]+"\}', fh.read()):
                before.add(f"entity.{a}.{b}")
    body = ",\n".join(f'            {{"{a}", "{b}", "{c}"}}' for a, b, c in rows)
    with open(TABLE, "w", encoding="utf-8", newline="\n") as fh:
        fh.write("package com.linkyoshi90.harmontide.registry;\n\n"
                 "/** Generated by tools/gen_species_voices.py: species, slot, the vanilla sound it used. Do not edit by hand. */\n"
                 "public final class SpeciesVoiceTable {\n"
                 "    public static final String[][] ROWS = {\n" + body + "\n    };\n\n"
                 "    private SpeciesVoiceTable() {\n    }\n}\n")

    path = os.path.join(ASSETS, "sounds.json")
    with open(path, encoding="utf-8") as fh:
        sounds = json.load(fh)
    wanted = {f"entity.{a}.{b}": c for a, b, c in rows}
    for key in [k for k, v in sounds.items() if k in before and redirect(v) and k not in wanted]:
        del sounds[key]                                                    # a slot that no longer exists
    kept = 0
    for key, vanilla in wanted.items():
        if key in sounds and not redirect(sounds[key]):
            kept += 1                                                      # a real recording: leave it be
            continue
        sounds[key] = {"subtitle": "subtitles.harmontide." + key, "sounds": [{"name": vanilla, "type": "event"}]}
    with open(path, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(json.dumps(sounds, indent=2, ensure_ascii=False))

    with open(os.path.join(ASSETS, "lang", "en_us.json"), encoding="utf-8") as fh:
        lang = json.load(fh)
    subs = {}
    for a, b, _ in rows:
        name = lang.get(f"entity.harmontide.{a}", a.replace("_", " ").title())
        subs[f"subtitles.harmontide.entity.{a}.{b}"] = f"{name} {VERB[b]}"
    add_lang(subs)
    print(f"{len(rows)} voices for {len({r[0] for r in rows})} species; {kept} already have a recording")


if __name__ == "__main__":
    main(sys.argv[1])
