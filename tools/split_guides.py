#!/usr/bin/env python3
"""Splits the journal's long guide pages so nothing is cut off (entity/Journal.java, entity/GuidePages.java).

    python tools/split_guides.py

A written book's page shows 14 lines of 114 pixels. The server can't measure text in the reader's font, so the splitting is done here:
each guide (and each kind's signature, under her name) whose title and text don't fit is cut at sentence ends into parts, written as `journal.harmontide.guide.<name>.p<n>`
lines next to the whole text (which stays the source to edit), and the page count goes into GuidePages.java. The widths are vanilla's
default font. gen_milk_assets.add_lang runs this whenever it writes a guide line. Can be run twice.
"""
import json
import os
import re

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
LANG = os.path.join(REPO, "src", "main", "resources", "assets", "harmontide", "lang", "en_us.json")
JOURNAL = os.path.join(REPO, "src", "main", "java", "com", "linkyoshi90", "harmontide", "entity", "Journal.java")
OUT = os.path.join(REPO, "src", "main", "java", "com", "linkyoshi90", "harmontide", "entity", "GuidePages.java")
PREFIX = "journal.harmontide.guide."
SIG = r"journal\.harmontide\.[a-z0-9_]+\.signature"
LINES, WIDTH = 14, 114
EXTRA = {"festivals": 2}                     # lines Journal adds under the last page (the next festival)

NARROW = {" ": 4, "i": 2, "l": 3, "t": 4, "f": 5, "k": 5, ".": 2, ",": 2, ":": 2, ";": 2, "!": 2, "'": 2, "I": 4, "(": 5, ")": 5,
          '"': 5, "|": 2, "`": 3, "*": 5, "<": 5, ">": 5, "[": 4, "]": 4, "{": 5, "}": 5, "’": 2, "—": 9}


def width(word, bold=False):
    return sum(NARROW.get(c, 6) + (1 if bold else 0) for c in word)


def lines(text, bold=False):
    n = 0
    for para in text.split("\n"):
        n += 1
        cur = 0
        for word in para.split(" "):
            w = width(word, bold)
            if cur and cur + width(" ", bold) + w <= WIDTH:
                cur += width(" ", bold) + w
            elif cur:
                n += 1
                cur = w
            else:
                cur = w
    return n


def parts(title, text, extra=0):
    room = LINES - lines(title, True) - 1                                       # the title, then a blank line
    if lines(text) + extra <= room:
        return [text]
    words, out, cur = text.split(" "), [], []
    for word in words:
        if lines(" ".join(cur + [word])) <= room:
            cur.append(word)
            continue
        ends = [i for i, w in enumerate(cur) if w[-1] in ".!?"]                 # cut at the last sentence end, if it leaves the page
        if not ends or ends[-1] + 1 < len(cur) // 3:                            # (a third full at least), else after a comma
            ends = [i for i, w in enumerate(cur) if w[-1] in ",;:"]
        cut = ends[-1] + 1 if ends and ends[-1] + 1 >= len(cur) // 3 else len(cur)
        out.append(" ".join(cur[:cut]))
        cur = cur[cut:] + [word]
    if cur:
        out.append(" ".join(cur))
    while extra and lines(out[-1]) + extra > room:                               # room on the last page for what Journal adds
        sentences = re.split(r"(?<=[.;:!?])\s+", out[-1])
        if len(sentences) < 2:
            break
        out[-1] = " ".join(sentences[:-1])
        out.append(sentences[-1])
    return out


def main():
    with open(LANG, encoding="utf-8") as fh:
        lang = json.load(fh)
    src = open(JOURNAL, encoding="utf-8").read()
    guides = re.findall(r'"([a-z_]+)"', re.search(r"GUIDE = List\.of\(([^)]*)\)", src).group(1))
    for k in [k for k in lang if re.fullmatch(re.escape(PREFIX) + r"[a-z_]+\.p\d+", k) or re.fullmatch(SIG + r"\.p\d+", k)]:
        del lang[k]
    counts = {}
    for g in guides:
        split = parts(lang[PREFIX + g + ".title"], lang[PREFIX + g], EXTRA.get(g, 0))
        if len(split) > 1:
            counts[g] = len(split)
            for i, part in enumerate(split, 1):
                lang[f"{PREFIX}{g}.p{i}"] = part
    signatures = {}
    for k in [k for k in lang if re.fullmatch(SIG, k)]:                         # what she does, on its own page(s) under her name
        kind = k[len("journal.harmontide."):-len(".signature")]
        split = parts(lang.get("entity.harmontide." + kind, kind), lang[k])
        if len(split) > 1:
            signatures[kind] = len(split)
            for i, part in enumerate(split, 1):
                lang[f"{k}.p{i}"] = part
    with open(LANG, "w", encoding="utf-8", newline="\n") as fh:
        json.dump(lang, fh, indent=2, ensure_ascii=False)
        fh.write("\n")
    entries = ",\n".join(f'            Map.entry("{g}", {n})' for g, n in counts.items())
    sig_entries = ",\n".join(f'            Map.entry("{g}", {n})' for g, n in sorted(signatures.items()))
    java = f"""package com.linkyoshi90.harmontide.entity;

import java.util.Map;

/** Generated by tools/split_guides.py: how many book pages each long journal guide, and each kind's signature, takes (the rest take one). Do not edit. */
public final class GuidePages {{
    public static final Map<String, Integer> PAGES = Map.ofEntries(
{entries});
    public static final Map<String, Integer> SIGNATURES = Map.ofEntries(
{sig_entries});

    private GuidePages() {{
    }}

    public static int of(String guide) {{
        return PAGES.getOrDefault(guide, 1);
    }}

    public static int signature(String kind) {{
        return SIGNATURES.getOrDefault(kind, 1);
    }}
}}
"""
    with open(OUT, "w", encoding="utf-8", newline="\r\n") as fh:
        fh.write(java)
    print(f"guides split: {len(counts)} of {len(guides)} take more than a page; signatures: {len(signatures)}")


if __name__ == "__main__":
    main()
