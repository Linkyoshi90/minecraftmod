#!/usr/bin/env python3
"""Writes SOUNDS.md: every sound the mod plays, and what replacing it with a custom sound takes.

    python tools/sound_register.py

Part 1 lists the mod's own sound events (assets/harmontide/sounds.json). They still point at vanilla files, so
replacing one is a resource change only. Part 2 lists every place the Java code plays a vanilla `SoundEvents.*`
directly (the girl families, mostly). Those need their own sound event first (see TODO.md section 3).
Re-run after adding sounds or species. The register is generated from the code, so it never goes stale.
"""
import json
import os
import re

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SOUNDS = os.path.join(REPO, "src", "main", "resources", "assets", "harmontide", "sounds.json")
JAVA = os.path.join(REPO, "src", "main", "java")
OUT = os.path.join(REPO, "SOUNDS.md")

USE = re.compile(r"SoundEvents\.([A-Z0-9_]+)")
METHOD = re.compile(r"^\s*(?:@\w+\s+)*(?:public|protected|private|static|final|\s)+[\w<>\[\], ?.]+\s+(\w+)\s*\([^;]*$")


def mod_events():
    data = json.load(open(SOUNDS, encoding="utf-8"))
    rows = []
    for event, spec in data.items():
        files = []
        for s in spec.get("sounds", []):
            s = {"name": s} if isinstance(s, str) else s
            files.append(s["name"] + (f" (pitch {s['pitch']})" if "pitch" in s else ""))
        # group the variations of one sound (idle1..idle6) into one entry
        short = sorted(dict.fromkeys(re.sub(r"\d+( \(pitch [\d.]+\))?$", r"*\1", f) for f in files))
        rows.append((event, ", ".join(short)))
    return rows


def java_uses():
    out = {}
    for root, _, names in os.walk(JAVA):
        if os.sep + "gametest" in root:
            continue
        for n in sorted(names):
            if not n.endswith(".java"):
                continue
            path = os.path.join(root, n)
            rel = os.path.relpath(path, REPO).replace(os.sep, "/")
            method = "(field)"
            for i, line in enumerate(open(path, encoding="utf-8"), 1):
                m = METHOD.match(line)
                if m and m.group(1) not in ("if", "for", "while", "switch", "return", "new"):
                    method = m.group(1)
                for ev in dict.fromkeys(USE.findall(line)):
                    ctx = line.strip()
                    out.setdefault((n[:-5], rel), []).append((i, method, ev, ctx if len(ctx) <= 140 else ctx[:137] + "..."))
    return out


def esc(s):
    return s.replace("|", "\\|")


def main():
    mod = mod_events()
    uses = java_uses()
    n_uses = sum(len(v) for v in uses.values())
    distinct = sorted({ev for v in uses.values() for _, _, ev, _ in v})
    L = ["# Sound register", "",
         "GENERATED by `tools/sound_register.py` (re-run it after changes). Every sound Harmontide plays and how to swap it for a custom one.", "",
         f"- **{len(mod)} mod sound events** (part 1): already have their own id. Replacing one is a resource change only.",
         f"- **{n_uses} direct vanilla calls** using {len(distinct)} different vanilla sounds (part 2): these need a sound event of their own first.", "",
         "## How to replace a sound", "",
         "1. Put the file at `src/main/resources/assets/harmontide/sounds/<folder>/<name>.ogg` (mono Ogg Vorbis, so it fades with distance).",
         "2. In `assets/harmontide/sounds.json`, change that event's `\"name\"` to `\"harmontide:<folder>/<name>\"`. List several files to get random variations.",
         "3. For part 2 sounds, first register an event `entity.<species>.<slot>` in `ModSounds` (and `sounds.json` + subtitle), then point the listed line at it. TODO.md section 3 has the plan.", "",
         "## 1. Mod sound events (resource change only)", "",
         "| Event | Plays now (vanilla) | Custom file, for example |", "|---|---|---|"]
    for event, files in mod:
        folder = event.split(".")[1] if event.count(".") >= 2 else "misc"
        L.append(f"| `{event}` | {esc(files)} | `sounds/{folder}/{event.split('.')[-1]}.ogg` |")
    L += ["", "## 2. Direct vanilla calls (need a sound event first)", "",
          "Grouped by class. The code column shows the condition, which usually names the species.", ""]
    for (cls, rel), rows in sorted(uses.items()):
        L += [f"### {cls}", "", "| Line | Method | Vanilla sound | Code |", "|---|---|---|---|"]
        for line, method, ev, ctx in rows:
            L.append(f"| [{line}]({rel}:{line}) | `{method}` | `{ev}` | `{esc(ctx)}` |")
        L.append("")
    L += ["## Vanilla sounds in use (part 2)", "", ", ".join(f"`{e}`" for e in distinct), ""]
    with open(OUT, "w", encoding="utf-8", newline="\n") as fh:
        fh.write("\n".join(L))
    print(f"SOUNDS.md: {len(mod)} mod events, {n_uses} direct calls in {len(uses)} classes ({len(distinct)} vanilla sounds)")


if __name__ == "__main__":
    main()
