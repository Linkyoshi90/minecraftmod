#!/usr/bin/env python3
"""Where each girl's chest is (2026-11-13, entity/Lactation#chest): read from her model, written as registry/ChestTable.java.

    python tools/gen_chest_table.py

For every species in GirlSpecies.java: the chest's height as a share of her model height (halfway between the body bone's pivot and the
head bone's, a little up) and how far ahead of her feet it is, as a share of her model height (the front of her body cubes). Centaurs,
giraffes, lamias and the like carry their torso high or forward, which a fixed guess got wrong (milk dripped from a giraffe's back).
Re-run after adding species or changing a body.
"""
import json
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
GEO = os.path.join(ROOT, "src", "main", "resources", "assets", "harmontide", "geo", "entity")
SPECIES = os.path.join(ROOT, "src", "main", "java", "com", "linkyoshi90", "harmontide", "entity", "girl", "GirlSpecies.java")
OUT = os.path.join(ROOT, "src", "main", "java", "com", "linkyoshi90", "harmontide", "registry", "ChestTable.java")


def main():
    rows = []
    for m in re.finditer(r'^\s+[A-Z0-9_]+\("([a-z0-9_]+)", Family\.[A-Z_]+, [0-9.]+F, ([0-9.]+)F', open(SPECIES, encoding="utf-8").read(), re.M):
        sp, model_h = m.group(1), float(m.group(2))
        path = os.path.join(GEO, sp + ".geo.json")
        if not os.path.exists(path):
            continue
        bones = {b["name"]: b for b in json.load(open(path, encoding="utf-8"))["minecraft:geometry"][0]["bones"]}
        if "body" not in bones or "head" not in bones:
            continue
        y = (bones["body"]["pivot"][1] + bones["head"]["pivot"][1]) / 2 + 1.5
        cubes = bones["body"].get("cubes", [])
        front = -min((c["origin"][2] for c in cubes), default=-2.0)
        rows.append((sp, round(y / model_h, 3), round(max(0.0, front) / model_h, 3)))
    lines = ",\n".join(f'            Map.entry("{sp}", new float[] {{{h}F, {f}F}})' for sp, h, f in rows)
    java = f"""package com.linkyoshi90.harmontide.registry;

import java.util.Map;

/** Generated by tools/gen_chest_table.py: each girl's chest as {{height, distance ahead}}, both shares of her height. Do not edit. */
public final class ChestTable {{
    public static final Map<String, float[]> CHEST = Map.ofEntries(
{lines});

    private ChestTable() {{}}
}}
"""
    open(OUT, "w", encoding="utf-8", newline="\n").write(java)
    print(len(rows), "species")


if __name__ == "__main__":
    main()
